#!/usr/bin/env bash
# Releases Sift It: builds the app with the sift-it it ships with (ENGINE_VERSION), signs and notarizes it, publishes
# it as a GitHub release, and writes Casks/sift-it.rb to jwa91/homebrew-tap. That one cask is all there is to install:
# the app, and the `sift-it` command, linked from inside it. sift-it's own releases publish its binaries, which this
# fetches; the cask is released from here.
#
#   scripts/release.sh X.Y.Z        a release (through `make release`)
#   scripts/release.sh --snapshot   build, archive, and render the cask into dist/, signed ad hoc; publish nothing
#
# It needs no secrets of its own: signing and notarizing use the releasing Mac's keychain (scripts/codesign.sh), and the
# GitHub release and the cask use your gh login.
set -euo pipefail

OWNER=jwa91
REPO=sift-it-mac
TAP=homebrew-tap
DESCRIPTION="One search bar for your files, by what's in them"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

plist_version() {
  /usr/libexec/PlistBuddy -c "Print :CFBundleShortVersionString" "$1"
}

snapshot=false
if [[ "${1:-}" == "--snapshot" ]]; then
  snapshot=true
  version="$(plist_version Resources/Info.plist)"
else
  version="${1:?usage: scripts/release.sh X.Y.Z | --snapshot}"
fi
tag="v$version"
archive="sift-it-mac_${version}_darwin_arm64.zip"
app="dist/Sift It.app"

rm -rf dist
mkdir -p dist

# Build, and check it is the version being released.
scripts/bundle.sh
built="$(plist_version "build/Sift It.app/Contents/Info.plist")"
if [[ "$built" != "$version" ]]; then
  echo "release: the app says $built, not $version (Resources/Info.plist)" >&2
  exit 1
fi
ditto "build/Sift It.app" "$app"

# Sign, notarize and staple: a release always is; a snapshot (CI's, or a dry run) stays signed ad hoc.
if $snapshot; then
  echo "snapshot: not signed with a Developer ID"
else
  scripts/codesign.sh "$app"
fi

# The archive (the app, as ditto keeps its signature) and its checksum.
ditto -c -k --keepParent "$app" "dist/$archive"
(cd dist && shasum -a 256 "$archive" > checksums.txt)
sha256="$(cut -d' ' -f1 dist/checksums.txt)"

# The cask: the app, and sift-it's command from inside it. The app sets the rest up when it's first opened.
cat > dist/sift-it.rb <<EOF
# This file was generated by sift-it-mac's scripts/release.sh. DO NOT EDIT.
cask "sift-it" do
  version "$version"
  sha256 "$sha256"

  url "https://github.com/$OWNER/$REPO/releases/download/v#{version}/sift-it-mac_#{version}_darwin_arm64.zip"
  name "Sift It"
  desc "$DESCRIPTION"
  homepage "https://github.com/$OWNER/$REPO"

  livecheck do
    skip "Auto-generated on release."
  end

  conflicts_with cask: "$OWNER/tap/sift-it-mac"
  depends_on arch: :arm64
  depends_on macos: :sonoma

  app "Sift It.app"
  binary "#{appdir}/Sift It.app/Contents/Helpers/sift-it"

  # An upgrade takes the background indexer away too; the app puts it back when it opens.
  uninstall launchctl: ["local.sift-it.indexer", "local.sift-it.engine"],
            quit:      "dev.sift-it.mac"

  # The models stay: they're in the shared Hugging Face cache (~/.cache/huggingface/hub), which other apps may use.
  zap trash: [
    "~/Library/Application Support/Sift It",
    "~/Library/Caches/sift-it",
    "~/Library/Caches/sift-it-transcribe",
    "~/Library/LaunchAgents/local.sift-it.engine.plist",
    "~/Library/LaunchAgents/local.sift-it.indexer.plist",
    "~/Library/Preferences/dev.sift-it.mac.plist",
  ]

  caveats <<~EOS
    Open Sift It to set it up: it downloads its model and asks which folders to search.
    Then Control-Shift-Space opens the search from any app.
  EOS
end
EOF

# The release notes: this version's section of the changelog.
awk -v version="$version" '
  $0 ~ "^## \\[" version "\\]" { inside = 1; next }
  /^## \[/ { inside = 0 }
  inside { print }
' CHANGELOG.md > dist/notes.md
if [[ ! -s dist/notes.md ]]; then
  echo "release: CHANGELOG.md has no section for [$version]" >&2
  $snapshot || exit 1
fi

if $snapshot; then
  echo "snapshot in dist/: $archive ($sha256), sift-it.rb"
  exit 0
fi

# The GitHub release, with your gh login.
gh release create "$tag" "dist/$archive" dist/checksums.txt \
  --repo "$OWNER/$REPO" --title "$tag" --notes-file dist/notes.md --verify-tag

# The cask, committed to the tap through the API with your gh login (tokens act through the API; people push over
# SSH: tap ADR 0002).
existing="$(gh api "repos/$OWNER/$TAP/contents/Casks/sift-it.rb" --jq .sha 2>/dev/null || true)"
args=(-X PUT "repos/$OWNER/$TAP/contents/Casks/sift-it.rb"
  -f message="feat(sift-it): cask update to $tag"
  -f content="$(base64 < dist/sift-it.rb | tr -d '\n')"
  -f branch=main)
[[ -n "$existing" ]] && args+=(-f sha="$existing")
gh api "${args[@]}" --jq '.commit.html_url'

echo "released $tag: brew install $OWNER/tap/sift-it"
